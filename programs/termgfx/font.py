"""A 5x5 block font for big banners."""

_GLYPHS = {
    "A": [".###.", "#...#", "#####", "#...#", "#...#"],
    "B": ["####.", "#...#", "####.", "#...#", "####."],
    "C": [".####", "#....", "#....", "#....", ".####"],
    "D": ["####.", "#...#", "#...#", "#...#", "####."],
    "E": ["#####", "#....", "####.", "#....", "#####"],
    "H": ["#...#", "#...#", "#####", "#...#", "#...#"],
    "I": ["#####", "..#..", "..#..", "..#..", "#####"],
    "L": ["#....", "#....", "#....", "#....", "#####"],
    "M": ["#...#", "##.##", "#.#.#", "#...#", "#...#"],
    "N": ["#...#", "##..#", "#.#.#", "#..##", "#...#"],
    "O": [".###.", "#...#", "#...#", "#...#", ".###."],
    "P": ["####.", "#...#", "####.", "#....", "#...."],
    "R": ["####.", "#...#", "####.", "#..#.", "#...#"],
    "S": [".####", "#....", ".###.", "....#", "####."],
    "T": ["#####", "..#..", "..#..", "..#..", "..#.."],
    "U": ["#...#", "#...#", "#...#", "#...#", ".###."],
    "W": ["#...#", "#...#", "#.#.#", "##.##", "#...#"],
    "Y": ["#...#", ".#.#.", "..#..", "..#..", "..#.."],
    "1": ["..#..", ".##..", "..#..", "..#..", ".###."],
    "3": ["####.", "....#", ".###.", "....#", "####."],
    "4": ["#..#.", "#..#.", "#####", "...#.", "...#."],
    ".": [".....", ".....", ".....", ".....", "..#.."],
    "!": ["..#..", "..#..", "..#..", ".....", "..#.."],
    " ": [".....", ".....", ".....", ".....", "....."],
}

HEIGHT = 5


def render(text, gap=1):
    """Return the banner as a list of 5 strings made of '#' and '.'."""
    rows = [""] * HEIGHT
    for i, ch in enumerate(str(text).upper()):
        g = _GLYPHS.get(ch, _GLYPHS[" "])
        for r in range(HEIGHT):
            rows[r] += ("." * gap if i else "") + g[r]
    return rows


def width(text, gap=1):
    n = len(str(text))
    return n * 5 + max(0, n - 1) * gap
